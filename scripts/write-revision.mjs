#!/usr/bin/env node
/**
 * write-revision.mjs — T-308 Slice A, Contract A2/A3/A3b.
 *
 *     node scripts/write-revision.mjs                    # unset/invalid -> placeholder, exit 0
 *     node scripts/write-revision.mjs --require           # unset/invalid -> writes NOTHING, exit 1
 *     node scripts/write-revision.mjs --out <path>         # write somewhere other than the default
 *
 * Writes apps/erp/src/generated/revision.ts, a plain module with no imports of its own, baked
 * into `.next` at build time so a value compiled into the artifact can never disagree with the
 * code it labels (the alternative — reading a file at runtime — would report the NEW release's
 * sha while the process is still executing the OLD build, if a deploy's symlink swap succeeds
 * but its restart does not take).
 *
 * Reads exactly one input, `DEPLOY_REVISION_SHA`, and never invents a value: no `git rev-parse`
 * fallback, no `"dev"`, no empty string, no timestamp-only record. DEF-311 is the standing proof
 * that a plausible-looking wrong value costs more than an honest absence — so the unset/invalid
 * path either writes the honest placeholder (`sha: 'unknown', builtAt: null`) or, under
 * `--require`, refuses outright rather than let a production artifact ship unable to say what it is.
 *
 * ⛔ `--out` is an ARGV FLAG, deliberately not an env var (Contract A3b). An env var is inherited
 * by every child process and can be set far from the command it affects — if something unrelated
 * set an output-path env var in the deploy environment, the build would write the revision file
 * somewhere else and then compile in the untouched placeholder, with `--require` having PASSED
 * and nothing red anywhere. A flag can only be set at the call site.
 */
import { writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const DEFAULT_OUTPUT_PATH = join(repoRoot, 'apps', 'erp', 'src', 'generated', 'revision.ts');

const argv = process.argv.slice(2);
const outIndex = argv.indexOf('--out');
let OUTPUT_PATH = DEFAULT_OUTPUT_PATH;
if (outIndex !== -1) {
  const value = argv[outIndex + 1];
  if (!value || value.startsWith('--')) {
    // A bare `--out`, or one immediately followed by another flag instead of a path, must
    // refuse rather than silently fall back to the tracked path — that fallback is exactly the
    // file this flag exists to protect (Contract A3b).
    console.error(
      'write-revision: --out was not followed by a real path' +
        (value ? ` (got ${JSON.stringify(value)}, which looks like another flag)` : '') +
        '. Refusing to silently fall back to the default output path — that would write to the ' +
        'tracked file this flag exists to protect. Pass a path: --out <path>.',
    );
    process.exit(1);
  }
  OUTPUT_PATH = resolve(value);
}

const SHA_PATTERN = /^[0-9a-f]{40}$/;

// `sha` is either the fixed literal 'unknown' or already validated against SHA_PATTERN
// (hex digits only); `builtAt` is either null or this process's own toISOString() output.
// Neither can contain a quote or a backslash, so a single-quoted literal is safe as written —
// no escaping helper needed for inputs this narrow.
function fileContents(sha, builtAt) {
  const builtAtLiteral = builtAt === null ? 'null' : `'${builtAt}'`;
  return (
    '// GENERATED by scripts/write-revision.mjs (T-308 Slice A, Contract A2) — DO NOT EDIT BY\n' +
    '// HAND. The committed content here is the placeholder; the CI runner overwrites it in\n' +
    "// place before `next build`, and nothing commits that overwrite back.\n" +
    `export const REVISION = { sha: '${sha}', builtAt: ${builtAtLiteral} } as const;\n`
  );
}

const requireValid = argv.includes('--require');
const raw = process.env.DEPLOY_REVISION_SHA ?? '';
const valid = SHA_PATTERN.test(raw);

if (!valid) {
  if (requireValid) {
    console.error(
      'write-revision: DEPLOY_REVISION_SHA is ' +
        (raw === '' ? 'unset or empty' : `invalid (received ${JSON.stringify(raw)})`) +
        ' and --require was passed. Refusing to write a placeholder or a guessed value for a ' +
        'production artifact that must be able to say what it is (DEF-311) — writing nothing.',
    );
    process.exit(1);
  }
  writeFileSync(OUTPUT_PATH, fileContents('unknown', null));
  console.log('write-revision: no valid DEPLOY_REVISION_SHA — wrote the placeholder.');
  process.exit(0);
}

writeFileSync(OUTPUT_PATH, fileContents(raw, new Date().toISOString()));
console.log(`write-revision: wrote ${raw}`);
