/**
 * Generates a line-range table of contents into the top of a long document.
 *
 * **Why generated and not hand-written.** A TOC carrying line numbers is stale the moment the
 * document is edited, and a stale line-range TOC is worse than none: it sends the reader to the
 * wrong place with full confidence. Hand-maintaining one would be exactly the second copy of a
 * fact this project keeps refusing to create.
 *
 * So the document is the source, this regenerates from it, and
 * `tests/unit/toc-freshness.test.ts` fails the build when the two disagree.
 *
 * The point is offset/limit reads: an agent reads ~30 lines of index and then the one section it
 * needs, instead of pulling 1,680 lines to answer one question.
 *
 *   npm run toc          # rewrite the TOCs
 *   npm run toc -- --check   # exit 1 if any is stale (what CI runs)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const START = '<!-- TOC:START — generated by `npm run toc`. Do not edit by hand. -->';
const END = '<!-- TOC:END -->';

/** Documents long enough that reading them whole to answer one question is wasteful. */
export const TOC_TARGETS = ['PROJECT_BIBLE.md', 'docs/POSTING-PATTERNS.md'] as const;

interface Heading {
  readonly level: number;
  readonly text: string;
  readonly line: number;
}

function headings(body: string): Heading[] {
  const out: Heading[] = [];
  let inFence = false;
  body.split('\n').forEach((raw, idx) => {
    // A ``` fence can contain lines that look like headings. Counting those would produce a TOC
    // pointing into a code block.
    if (/^\s*```/.test(raw)) inFence = !inFence;
    if (inFence) return;
    const m = /^(#{2,3})\s+(.*\S)\s*$/.exec(raw);
    if (m) out.push({ level: m[1]!.length, text: m[2]!, line: idx + 1 });
  });
  return out;
}

/** Strip markdown emphasis and links so the index reads as plain text. */
function plain(s: string): string {
  return s
    .replace(/\[([^\]]+)\]\([^)]*\)/g, '$1')
    .replace(/[*_`]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}

export function buildToc(body: string, totalLines: number): string {
  const hs = headings(body);
  const rows = hs.map((h, i) => {
    const end = i + 1 < hs.length ? hs[i + 1]!.line - 1 : totalLines;
    const indent = h.level === 3 ? '  ' : '';
    return `${indent}- \`${String(h.line).padStart(4)}–${String(end).padEnd(4)}\` ${plain(h.text)}`;
  });
  return [
    START,
    '',
    '> **Read this index, then `offset`/`limit` to the section you need.** Line ranges are',
    '> generated from the headings below and verified by `tests/unit/toc-freshness.test.ts` —',
    '> if they are wrong, the build fails rather than misdirecting you.',
    '',
    ...rows,
    '',
    END,
  ].join('\n');
}

/** Returns the file content with a fresh TOC, without writing it. */
export function withFreshToc(content: string): string {
  const hasBlock = content.includes(START) && content.includes(END);

  // On a REGENERATION the title sits ABOVE the existing TOC block, so the head must be taken
  // from before START — not from after END. Slicing from END dropped the title entirely: correct
  // on the first run, destructive on the second. It deleted the title of both documents before
  // `toc-freshness.test.ts` caught it, which is precisely why an idempotency check exists.
  let head: string;
  let rest: string;

  if (hasBlock) {
    head = content.slice(0, content.indexOf(START)).replace(/\n+$/, '');
    rest = content.slice(content.indexOf(END) + END.length).replace(/^\n+/, '');
  } else {
    const lines = content.split('\n');
    const titleIdx = lines.findIndex((l) => /^#\s+\S/.test(l));
    head = titleIdx >= 0 ? lines.slice(0, titleIdx + 1).join('\n') : '';
    rest = (titleIdx >= 0 ? lines.slice(titleIdx + 1).join('\n') : content).replace(/^\n+/, '');
  }

  // A document with no `# ` title would otherwise lose its opening lines. Refuse rather than
  // guess — silently reshaping a file is how the bug above happened.
  if (head.trim() === '') {
    throw new Error('withFreshToc: no title line found, refusing to rewrite (a TOC must sit under a title)');
  }

  // Line numbers must describe the FINAL file, so they are computed against the assembled
  // result rather than the body alone — a TOC that omits its own height points everywhere but
  // where it says.
  let toc = buildToc(rest, rest.split('\n').length);
  for (let pass = 0; pass < 4; pass++) {
    const assembled = `${head}\n\n${toc}\n\n${rest}`;
    const offset = assembled.split('\n').length - rest.split('\n').length;
    const shifted = buildToc(rest, rest.split('\n').length)
      .split('\n')
      .map((l) => {
        const m = /^(\s*- `)\s*(\d+)–(\d+)(\s*`.*)$/.exec(l);
        if (!m) return l;
        return `${m[1]}${String(Number(m[2]) + offset).padStart(4)}–${String(Number(m[3]) + offset).padEnd(4)}${m[4]}`;
      })
      .join('\n');
    if (shifted === toc) break;
    toc = shifted;
  }
  return `${head}\n\n${toc}\n\n${rest}`;
}

function main(): void {
  const check = process.argv.includes('--check');
  const root = process.cwd();
  let stale = 0;

  for (const rel of TOC_TARGETS) {
    const p = join(root, rel);
    const current = readFileSync(p, 'utf8');
    const fresh = withFreshToc(current);
    if (current === fresh) {
      console.log(`  ok     ${rel}`);
      continue;
    }
    stale++;
    if (check) {
      console.error(`  STALE  ${rel} — run \`npm run toc\``);
    } else {
      writeFileSync(p, fresh, 'utf8');
      console.log(`  wrote  ${rel}`);
    }
  }

  if (check && stale > 0) process.exitCode = 1;
}

if (process.argv[1] && process.argv[1].endsWith('gen-toc.ts')) main();
