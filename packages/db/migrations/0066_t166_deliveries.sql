-- ---------------------------------------------------------------------------------------------
-- ⭐ A received line must carry a received quantity, and a SHORT one must explain itself.
--
-- v1's rule, and the reason is a supplier conversation rather than bookkeeping: a line that
-- arrived short is a fact about a vendor, and an unexplained shortage is a fact nobody can act on.
-- ⚠️ Enforced as a trigger rather than a CHECK because it needs the delivery's own status.
CREATE FUNCTION "delivery_lines_shortage_explained"() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
	delivery_status text;
BEGIN
	SELECT "status" INTO delivery_status FROM "deliveries" WHERE "id" = NEW."delivery_id";
	IF delivery_status <> 'received' THEN RETURN NEW; END IF;

	IF NEW."received_quantity" IS NULL THEN
		RAISE EXCEPTION 'a received delivery line must carry a received quantity (line %)', NEW."line_no";
	END IF;

	IF NEW."received_quantity" < NEW."ordered_quantity" AND NEW."shortage_reason" IS NULL THEN
		RAISE EXCEPTION 'line % received short (% of %) and must carry a shortage reason',
			NEW."line_no", NEW."received_quantity", NEW."ordered_quantity";
	END IF;

	-- ⭐ Over-receipt is ALLOWED — suppliers legitimately send extra — but only deliberately.
	-- v1 made this an explicit, manager-gated flag rather than a silent tolerance, and the
	-- distinction is the whole control: a cashier can never bypass the cap by accident.
	IF NEW."received_quantity" > NEW."ordered_quantity" AND NOT NEW."over_receipt_allowed" THEN
		RAISE EXCEPTION 'line % received over (% of %) without an over-receipt approval',
			NEW."line_no", NEW."received_quantity", NEW."ordered_quantity";
	END IF;

	RETURN NEW;
END;
$$;--> statement-breakpoint

CREATE TRIGGER "delivery_lines_shortage_explained_trg"
	BEFORE INSERT OR UPDATE ON "delivery_lines"
	FOR EACH ROW EXECUTE FUNCTION "delivery_lines_shortage_explained"();--> statement-breakpoint

