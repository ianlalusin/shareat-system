-- 0066 — T-166: deliveries. The only door stock enters by.
--
-- HAND-WRITTEN, like 0020-0065. See DEF-073 for why `db:generate` cannot be used here.
--
-- ⭐ Receiving is the pivotal event: quantity moves (0063), cost becomes a FIFO layer (0064), and
-- value posts to the ledger (0065). Until this table, none of those three had a caller.
--
-- ⚠️ Two controls live here as CHECK constraints rather than in the service, because both are the
-- kind that gets forgotten by a new write path:
--   1. The PHOTO GATE — a delivery or purchase without proof cannot be stored at all.
--   2. Supplier required for a supplier delivery; optional for a staff cash purchase.

CREATE TABLE "deliveries" (
	"id" uuid PRIMARY KEY DEFAULT uuidv7() NOT NULL,
	"org_id" uuid NOT NULL,
	"store_id" uuid NOT NULL,
	"kind" text NOT NULL,
	"supplier_id" uuid,
	"reference_no" text,
	"delivered_on" date NOT NULL,
	"status" text DEFAULT 'draft' NOT NULL,
	"proof_file_id" uuid,
	"received_at" timestamp with time zone,
	"received_by" uuid,
	"voided_at" timestamp with time zone,
	"voided_by" uuid,
	"void_reason" text,
	"created_by" uuid NOT NULL,
	"created_at" timestamp with time zone DEFAULT now() NOT NULL,
	"updated_at" timestamp with time zone,
	CONSTRAINT "deliveries_kind_check" CHECK ("kind" IN ('supplier','purchase','commissary')),
	CONSTRAINT "deliveries_status_check" CHECK ("status" IN ('draft','received','void')),
	-- A supplier delivery names its supplier; a staff cash purchase may genuinely have no vendor.
	CONSTRAINT "deliveries_supplier_required_check"
		CHECK ("kind" <> 'supplier' OR "supplier_id" IS NOT NULL),
	-- ⭐ THE PHOTO GATE. A cash purchase with no paper is indistinguishable from no purchase at
	-- all, which is why v1 enforces this server-side and why it is a constraint here rather than a
	-- service check. ⚠️ A COMMISSARY delivery is exempt: it is system-generated by T-173's
	-- cross-store receipt, there is no paper to photograph, and the dispatch IS the evidence.
	CONSTRAINT "deliveries_proof_required_check"
		CHECK ("kind" = 'commissary' OR "proof_file_id" IS NOT NULL),
	CONSTRAINT "deliveries_received_shape_check"
		CHECK ("status" <> 'received' OR ("received_at" IS NOT NULL AND "received_by" IS NOT NULL)),
	CONSTRAINT "deliveries_void_shape_check"
		CHECK ("status" <> 'void' OR ("voided_at" IS NOT NULL AND "voided_by" IS NOT NULL AND "void_reason" IS NOT NULL))
);--> statement-breakpoint

