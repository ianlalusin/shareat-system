// Pure fingerprint-shape helpers. No crypto / Capacitor / navigator imports, so this is safe in
// both the enrolment server path and the clock-terminal client path. Ported from v1's
// fingerprint-core.ts (T-314 slice A); only `buildFingerprintDbEntries` is renamed, to
// `buildReaderEntries`, per the slice A contract.

/**
 * Max fingers enrolled per credential (primary + backup) to cut false-rejects.
 *
 * ⚠️ Mirrors the DB's own CHECK (`attendance-credentials.ts`, the fingerprint branch of
 * `attendance_credentials_shape_check`: `array_length(templates,1) between 1 and 2`) rather than
 * duplicating it. This is boundary validation on templates that have not reached Postgres yet
 * (a capture, before an insert is even attempted) — RULES §6 item 3 is about not re-implementing
 * enforcement the database owns as the point of truth, not about rejecting bad input early. The
 * CHECK remains the authority; a bypass of this guard is still caught at INSERT.
 */
export const MAX_FINGERS = 2;

/** True when a credential has at least one enrolled template. */
export function hasFingerprint(templates?: string[] | null): boolean {
  return (templates?.length ?? 0) > 0;
}

/** Validate capture input: 1..MAX_FINGERS non-empty string templates. Trims them. */
export function validateFingerprintTemplates(
  templates: unknown,
): { ok: true; templates: string[] } | { ok: false; reason: string } {
  if (!Array.isArray(templates)) return { ok: false, reason: 'Templates must be a list.' };
  if (templates.length < 1) return { ok: false, reason: 'Capture at least one fingerprint.' };
  if (templates.length > MAX_FINGERS) return { ok: false, reason: `At most ${MAX_FINGERS} fingers.` };
  const cleaned: string[] = [];
  for (const t of templates) {
    if (typeof t !== 'string' || !t.trim()) return { ok: false, reason: 'Empty/invalid template.' };
    cleaned.push(t.trim());
  }
  return { ok: true, templates: cleaned };
}

// Slot separator for per-finger native-DB ids (see buildReaderEntries).
// Safe: matchToken is generated by generateMatchToken() as pure hex ([0-9a-f]),
// which can never contain '#'.
const SLOT_SEP = '#';

/** Flatten enrolled credentials into the matcher DB: one {id, template} per template.
 *  Each template gets a UNIQUE id (`${matchToken}#${slotIndex}`), not the bare
 *  matchToken — the native 1:N matcher (ZKFingerService.save) registers one
 *  template per id, so two templates saved under the same id silently overwrite
 *  each other and only the last-loaded finger stays matchable. Skips rows
 *  missing a token or templates. */
export function buildReaderEntries(
  rows: { matchToken?: string | null; templates?: string[] | null }[],
): { id: string; template: string }[] {
  const out: { id: string; template: string }[] = [];
  for (const r of rows) {
    if (!r.matchToken || !r.templates?.length) continue;
    r.templates.forEach((template, slot) => {
      if (template) out.push({ id: `${r.matchToken}${SLOT_SEP}${slot}`, template });
    });
  }
  return out;
}

/** Resolve a native-DB id (as returned by the reader's identify()) back to the
 *  credential's real matchToken by stripping its per-slot suffix. An id with
 *  no suffix (unexpected — every id from buildReaderEntries has one) is
 *  returned unchanged rather than throwing, since a bad match should fail the
 *  downstream matchToken lookup, not the app. */
export function resolveFingerprintMatchToken(id: string): string {
  const i = id.lastIndexOf(SLOT_SEP);
  return i === -1 ? id : id.slice(0, i);
}
